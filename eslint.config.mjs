// ESLint flat config for `npm run lint`.
//
// Lint is not one of the seven "Required CI categories" in
// docs/development-guide.md §G11; it is an additional gate added on 2026-11-17
// so that style and correctness regressions are caught before review. §G11's
// rule that a script may only be run when `package.json` defines it applies
// here too: this file exists because `npm run lint` was approved together with
// the `eslint` and `typescript-eslint` development dependencies, not because
// the guide mentions the operation.
//
// Two deliberate constraints shape what is in this file:
//
//  1. The approved development dependencies are exactly `eslint` and
//     `typescript-eslint` (docs/development-guide.md §15, dependency review).
//     ESLint 10 no longer ships `@eslint/js`, and neither `@eslint/js` nor
//     `globals` was approved, so the ready-made `js.configs.recommended` preset
//     and the pre-baked `globals` map are unavailable. The TypeScript rules come
//     from `typescript-eslint`, whose recommended set already carries its own
//     adjustments to the core rules; the `.mjs` rules below are a hand-picked
//     subset of ESLint's bundled core rules — correctness rules that need no
//     host-globals map — not a copied preset.
//  2. `tsconfig.json` is a check-only config (`noEmit`) that turns on
//     `allowImportingTsExtensions` so `npm test` can run sources through
//     `node --experimental-strip-types`. The type-checked ruleset would need a
//     project service or a `project` per source set, so the plain
//     non-type-checked ruleset is used here; `npm run typecheck` remains the
//     gate for anything that needs type information.
//
// Run `npm run lint` after any rule change: this file is a policy document for
// the repository, so an unreachable rule or a silently unlinted file is worse
// than a missing rule.

import { defineConfig, globalIgnores } from 'eslint/config';
import tseslint from 'typescript-eslint';

export default defineConfig(
  // Never lint build output or vendor code: `dist/` is generated by
  // `npm run build` and `node_modules/` is third-party (§G12 audits it
  // separately through package-lock.json).
  globalIgnores(['dist/**', 'node_modules/**']),

  {
    // Everything under `src/` is TypeScript run through Node's type stripping.
    files: ['**/*.ts'],
    extends: [tseslint.configs.recommended],
    languageOptions: {
      ecmaVersion: 'latest',
      sourceType: 'module',
    },
  },

  {
    // CI helper scripts. These run on the GitHub runner as plain JavaScript,
    // not through the plugin sandbox, so they are linted as Node ESM.
    files: ['.github/scripts/**/*.mjs'],
    languageOptions: {
      ecmaVersion: 'latest',
      sourceType: 'module',
      // No `globals` package in the approved dependency set, so the host names
      // these two scripts actually touch are declared by hand. Adding a name
      // here is a deliberate act: a wrong entry silently stops `no-undef` from
      // catching a typo. Verified against the scripts on 2026-11-17.
      globals: {
        console: 'readonly',
        process: 'readonly',
      },
    },
    rules: {
      // Correctness subset of the core rules that does not depend on a
      // host-globals map.
      'no-cond-assign': 'error',
      'no-const-assign': 'error',
      'no-dupe-args': 'error',
      'no-dupe-class-members': 'error',
      'no-dupe-keys': 'error',
      'no-func-assign': 'error',
      'no-import-assign': 'error',
      'no-invalid-regexp': 'error',
      'no-irregular-whitespace': 'error',
      'no-obj-calls': 'error',
      'no-redeclare': 'error',
      'no-self-assign': 'error',
      'no-sparse-arrays': 'error',
      'no-undef': 'error',
      'no-unreachable': 'error',
      'no-unsafe-negation': 'error',
      'no-unused-vars': ['error', { args: 'after-used', caughtErrors: 'all' }],
      'use-isnan': 'error',
      'valid-typeof': 'error',
    },
  },
);
